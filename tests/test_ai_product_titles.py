"""Словарь должностей ai_automation должен знать вариант со словом «менеджер».

Повод 27.08.2026: вакансия «Менеджер по внедрению и сопровождению AI-продукта»
(Опен Сервис) — лучшее совпадение по требованиям за неделю — набирала 32 балла
при пороге 42. В словаре было «специалист по внедрению ии/ai», но не было формы
с «менеджер», и вакансия не получала бонус за совпадение должности.

Здесь же закреплены два кандидата, ОТКЛОНЁННЫЕ замером: голые «специалист по
внедрению» (33% профильных, тащит Битрикс24) и «внедрению и сопровождению»
(12%, тащит внедренцев CRM). Квалифицирующее слово обязательно.
"""
from src.matcher.pre_filter import CRITERIA, score_vacancy

_TITLES = CRITERIA["roles"]["ai_automation"]["titles_strong"]

_AI_PRODUCT = (
    "Быть основным контактным лицом первых клиентов продукта. Погружаться в бизнес "
    "клиентов, формировать технические задания для разработки, самостоятельно "
    "настраивать AI-агентов, развивать клиентов и совершать Upsale. Требуется опыт "
    "создания собственных AI-агентов для рабочих задач, работа с LLM и API. Удалённо."
)


class TestAiProductTitles:
    def test_manager_of_ai_product_scores_above_threshold(self):
        res = score_vacancy("Менеджер по внедрению и сопровождению AI-продукта",
                            _AI_PRODUCT, "ai_automation")
        assert res["passed_gate"], res["reasons"]
        assert res["score"] >= 42, f"балл {res['score']} ниже порога роли: {res['reasons']}"

    def test_strong_title_match_is_credited(self):
        res = score_vacancy("Менеджер по внедрению ИИ в бизнес-процессы",
                            _AI_PRODUCT, "ai_automation")
        assert any("сильное совпадение" in r for r in res["reasons"]), res["reasons"]

    def test_bare_implementation_titles_stay_out(self):
        """Отклонённые замером формулировки не должны просочиться в словарь."""
        for bad in ("специалист по внедрению", "внедрению и сопровождению",
                    "менеджер по внедрению", "руководитель внедрения"):
            assert bad not in _TITLES, (
                f"«{bad}» отклонён замером (тащит 1С/CRM/Битрикс), но попал в словарь")

    def test_qualifier_is_required_in_every_new_title(self):
        """У каждого титула про внедрение должно быть слово ии/ai/продукт."""
        for t in _TITLES:
            if "внедрен" in t:
                assert any(q in t for q in ("ии", "ai", "продукт")), \
                    f"титул «{t}» про внедрение без квалификатора — соберёт 1С и CRM"
