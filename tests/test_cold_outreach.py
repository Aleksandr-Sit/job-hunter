SALES = ("Менеджер по продажам. Удалённо. CRM, B2B, финтех, платежи. "
         "Обязанности: холодные звонки, 50 звонков в день.")


def test_cold_outreach_rejected_for_every_role():
    # Лучшая роль берётся по максимуму: отсев только в sales_remote пропустил бы
    # «Менеджера по работе с клиентами» через роль поддержки.
    for role in CRITERIA["roles"]:
        ok, reasons = passes_hard_gates("Менеджер по работе с клиентами", SALES, role)
        assert not ok and reasons[0].startswith("холодный поиск"), (role, reasons)


def test_cold_title_dropped_before_description():
    assert title_triage("Conference Sales Executive (cold calls)/Менеджер по продажам") == "drop"
    assert title_triage("Менеджер по продажам (без холодных звонков)") != "drop"


def test_no_cold_calls_is_not_penalised():
    # До 18.10.2026 «холодных звонков» в keywords_penalize срабатывало внутри
    # «без холодных звонков»: +6 за буст и −12 за штраф одной и той же фразе.
    text = "Менеджер по продажам. Удалённо. Входящие заявки, без холодных звонков. Финтех, CRM."
    res = score_vacancy("Менеджер по продажам", text, "sales_remote")
    assert res["passed_gate"]
    assert not any("нерелевантные" in r for r in res["reasons"]), res["reasons"]
