@pytest.mark.parametrize("phrase", [
    # hh 138489384
    "ДМС, включающий стоматологию и страховку для выезжающих за рубеж. "
    "Поддерживаем удаленный формат работы",
    # hh 138795294, 137699257
    "9 дней на прохождение; полностью удалённый формат и свободный график.",
    # hh 128668048
    "Через полгода можно работать полностью удаленно или из комфортного офиса в Москве; "
    "гибкий график",
    # замер 27.10 — эти три резались ложно, пока обещание искали только в _EXPLICIT_REMOTE
    # hh 138235344 (Apyflow)
    "Компания — Apyflow DMCC, Дубай. Команда распределённая, работаем удалённо.",
    "Оформление по ТК РФ, оплата в рублях. Удалённо из любой точки. Возможна релокация в Дубай.",
    # hh 137765593 «Специалист по внедрению ИИ»
    "ДМС; Индивидуально обсуждаем возможность удаленного формата работы с командировками "
    "в Москву;",
    # hh 138338181
    "Молодой, дружный коллектив; Возможен вариант удаленной работы, после испытательного срока;",
    # по просьбе владельца 27.10: «удалёнка после испытательного» другими словами
    "После испытательного срока возможна работа удаленно.",
    "В дальнейшем возможен перевод на удалённую работу.",
    "После испытательного срока — переход на удалёнку.",
    "Возможность работать из дома после испытательного срока.",
])
def test_text_promising_remote_keeps_penalty(phrase):
    r = _score(b'["HYBRID"]', "Москва", phrase + "\n")
    assert r["passed_gate"]
    assert "офис/гибрид в другом городе РФ, удалёнки нет" in r["reasons"]


def test_without_field_behaviour_unchanged():
    """Не дообогащённая вакансия (формата нет) скорится как раньше."""
    r = _score(None, "Москва")
    assert "remote" in r["reasons"]
