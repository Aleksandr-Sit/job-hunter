"""AI-должности, которые узнаются ТОЛЬКО по заголовку (titles_strong_title), 29.10.2026.

Четыре живые вакансии hh дошли бы до бота только через чужие роли или не дошли
вовсе: ai_automation давала им 26–40 при пороге 42 — «должность напрямую не
совпала». Словарь не знал «промпт-инженер», «интегратор AI-решений»,
«AI-оптимизатор» и «…по внедрению ИИ» после слова, отличного от «специалист» и
«менеджер». На полных текстах этих вакансий правка дала 26→66, 32→72, 28→68, 40→80.

Слова живут отдельным списком, потому что в описании они встречаются у чужих
ролей: «внедрение AI-решений» у продаж, «prompt engineering» у разработчиков.
Фиксатуры — пересказ вакансий, а не их текст.
"""
import pytest

from src.matcher.pre_filter import passes_hard_gates, score_vacancy

REMOTE = "Формат работы (hh): REMOTE\n"

LIVE = [
    # hh 138924401, LPTracker через «Сферу», удалёнка
    ("Промпт-инженер / Аккаунт-менеджер",
     REMOTE + "Развиваем голосовой искусственный интеллект. Настройка сценариев "
     "голосовых роботов под задачи клиентов, ведение клиентов после запуска, "
     "интеграции с CRM. Обучение за счёт компании."),
    # hh 138458820, xHuman
    ("Интегратор AI-решений в отделы продаж / CSM",
     REMOTE + "Запуск AI-агентов для ключевых клиентов: разбор воронки продаж, "
     "настройка агента, сопровождение после запуска. Работаем с ChatGPT и Claude."),
    # hh 138397270, Lenkep → iGaming-клиент
    ("AI-оптимизатор",
     REMOTE + "Ищем специалиста, который найдёт рутину в процессах команды и "
     "заменит её нейросетями: промпты, шаблоны, внутренние боты."),
    # hh 138266865, Гидфинанс, офис в Самаре
    ("Бизнес-ассистент по внедрению ИИ",
     "Формат работы (hh): ON_SITE\nПроизводство бытовой химии. Описание процессов "
     "и их автоматизация: n8n, Python, LLM. Подготовка регламентов.\nLocation: Самара"),
]


@pytest.mark.parametrize("title,text", LIVE, ids=[t for t, _ in LIVE])
def test_live_cases_reach_threshold(title, text):
    r = score_vacancy(title, text, "ai_automation")
    assert r["recommend"], (r["score"], r["reasons"])
    assert "сильное совпадение по должности" in r["reasons"]


@pytest.mark.parametrize("title", [
    "Промпт-инженер",
    "Промт-инженер",
    "Prompt-инженер / LLM Behavior Engineer",
    "Middle Prompt Engineer",
    "Эксперт по внедрению AI решений",
    "Инженер внедрения ИИ решений (в ИТ)",
    "Специалист по внедрению искусственного интеллекта",
    "Аналитик по внедрению ИИ",
])
def test_title_counts_for_role_gate(title):
    """Заголовок сам по себе — ролевое слово: в тексте нет «автоматизации»."""
    text = REMOTE + "Пишем и тестируем инструкции для нейросетей, разбираем ответы модели."
    ok, reasons = passes_hard_gates(title, text, "ai_automation")
    assert ok, f"«{title}» не прошёл гейт — {reasons}"
    assert "сильное совпадение по должности" in score_vacancy(title, text, "ai_automation")["reasons"]


def test_phrase_in_description_is_not_a_title():
    """Продажи, где «внедрение AI-решений» и «prompt engineering» только в тексте."""
    text = (REMOTE + "Продаём внедрение AI-решений и ИИ-решений для бизнеса. Консультации "
            "по внедрению ИИ, prompt engineering приветствуется, интегратор AI в команде.")
    r = score_vacancy("Менеджер по продажам", text, "ai_automation")
    assert "сильное совпадение по должности" not in r["reasons"], r["reasons"]


@pytest.mark.parametrize("title", [
    "Менеджер по продажам (IT-проекты, внедрение ИИ)",   # голое «внедрение ИИ» — не берём
    "Специалист по внедрению 1С",
    "Специалист по внедрению CRM Битрикс24",
    "Интегратор 1С",
    "SEO-оптимизатор",
    "Администратор Битрикс24 с опытом внедрения AI-инструментов",
])
def test_neighbours_stay_out(title):
    text = REMOTE + "Внедрение, настройка, сопровождение клиентов."
    r = score_vacancy(title, text, "ai_automation")
    assert "сильное совпадение по должности" not in r["reasons"], (title, r["reasons"])
